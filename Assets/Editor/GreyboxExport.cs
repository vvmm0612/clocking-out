using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using DeathNotice.Core;
using DeathNotice.Game;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using Stage = DeathNotice.Game.Stage;

/// <summary>
/// Writes each level's greybox as a reference for the artists:
///   docs/greybox/&lt;levelId&gt;.obj (+ .mtl) - one named object per anchor, "_set" for the scenery that is
///       not an anchor, "_program" for program-drawn things (water, glass, gauge needle; do not model them),
///       "_player_ref" = the 0.7-unit protagonist standing at the first Place, for scale.
///   docs/anchors.md - per level: every anchor's origin, greybox size, behaviours and clue.
/// Coordinates: Unity world units (1 unit = 1 m in Blender). The OBJ is written right-handed, Y up,
/// with X mirrored (the same conversion Unity applies to FBX), so Blender's default OBJ import
/// (Forward -Z, Up Y) shows it the way the game camera sees it, and an FBX exported from Blender
/// with "Apply Transform" lands back on the same spot.
///   Unity.exe -batchmode -quit -projectPath . -executeMethod GreyboxExport.Run -logFile Logs/greybox.log
/// </summary>
public static class GreyboxExport
{
    const string OutDir = "docs/greybox";
    const string AnchorsDoc = "docs/anchors.md";
    static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    public static void Run()
    {
        EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
        Directory.CreateDirectory(OutDir);
        var doc = new StringBuilder();
        doc.AppendLine("# 锚点表（灰盒参照）");
        doc.AppendLine();
        doc.AppendLine("由 `Assets/Editor/GreyboxExport.cs` 生成（`-executeMethod GreyboxExport.Run`），**不要手改**。改了 `StageLayouts.cs` 后重新运行。");
        doc.AppendLine("每关的灰盒 OBJ 在 `docs/greybox/<levelId>.obj`，导入 Blender 当作比例和位置参照（规则见 `docs/art-brief.md` 第 2 节）。");
        doc.AppendLine();
        doc.AppendLine("- **原点**：锚点在世界坐标里的位置（Unity 坐标，Y 向上，镜头从 -Z 方向看向 +Z）。替换模型的原点会和它对齐，不做任何缩放。");
        doc.AppendLine("- **灰盒包围盒**：该锚点灰盒外观的尺寸 宽×高×深（X×Y×Z），以及包围盒中心相对原点的偏移。模型大致占这块空间即可。");
        doc.AppendLine("- **spin / toggle / light**：该锚点有持续旋转、开关（或铰链）、点亮行为；模型里对应子节点命名 `spin`、`toggle`、`light`，没有就作用于整个模型。");
        doc.AppendLine("- **类型**：地点 = 表单 Place 栏的选项（主角站在原点上）；NPC = 人物（按班次被摆到不同地点）；其他 = 物件。");
        doc.AppendLine();
        foreach (LevelData level in LevelLoader.LoadAllFromResources())
        {
            Stage stage = StageBuilder.Build(level, null, false);
            try
            {
                WriteObj(level, stage);
                WriteTable(level, stage, doc);
            }
            finally
            {
                Object.DestroyImmediate(stage.gameObject);
            }
        }
        File.WriteAllText(AnchorsDoc, doc.ToString(), new UTF8Encoding(false));
        Debug.Log("[GreyboxExport] Wrote " + OutDir + "/*.obj and " + AnchorsDoc);
    }

    static string F(float v) { return v.ToString("0.###", Inv); }

    static bool IsProgram(Component c) { return c.GetComponentInParent<ProgramVisual>(true) != null; }

    static string GroupOf(Renderer r)
    {
        if (IsProgram(r)) return "_program";
        AnchorTag a = r.GetComponentInParent<AnchorTag>(true);
        return a != null ? a.id : StageBuilder.SetName;
    }

    static void WriteObj(LevelData level, Stage stage)
    {
        // Reference figure at the first Place.
        FieldData place = level.FindField(Simulator.PlaceField);
        AnchorTag first = place != null && place.options.Count > 0 ? stage.Find(place.options[0].id) : null;
        Figure refFig = Figure.Create(stage.transform, "_player_ref", stage.palette.player, 0.7f, false, null);
        refFig.transform.position = first != null ? first.StandPoint : Vector3.zero;

        var groups = new SortedDictionary<string, List<MeshRenderer>>(System.StringComparer.Ordinal);
        foreach (MeshRenderer r in stage.GetComponentsInChildren<MeshRenderer>(true))
        {
            MeshFilter mf = r.GetComponent<MeshFilter>();
            if (mf == null || mf.sharedMesh == null) continue;
            if (r.transform.IsChildOf(stage.player.transform) || r.transform.IsChildOf(stage.ghost.transform)) continue;
            string g = r.transform.IsChildOf(refFig.transform) ? "_player_ref" : GroupOf(r);
            List<MeshRenderer> list;
            if (!groups.TryGetValue(g, out list)) groups[g] = list = new List<MeshRenderer>();
            list.Add(r);
        }

        var obj = new StringBuilder();
        var mtl = new StringBuilder();
        var mats = new HashSet<string>();
        obj.AppendLine("# Clocking Out greybox reference: " + level.id + " " + level.title);
        obj.AppendLine("# Generated by Assets/Editor/GreyboxExport.cs. Units = Unity units (m). X mirrored for right-handed tools.");
        obj.AppendLine("mtllib " + level.id + ".mtl");
        int vBase = 1, nBase = 1;
        foreach (var kv in groups)
        {
            obj.AppendLine("o " + kv.Key);
            obj.AppendLine("g " + kv.Key);
            foreach (MeshRenderer r in kv.Value)
            {
                Mesh m = r.GetComponent<MeshFilter>().sharedMesh;
                Transform t = r.transform;
                Color c = Mats.GetColor(r.sharedMaterial);
                string matName = "c_" + ColorUtility.ToHtmlStringRGB(c);
                if (mats.Add(matName))
                {
                    mtl.AppendLine("newmtl " + matName);
                    mtl.AppendLine("Kd " + F(c.r) + " " + F(c.g) + " " + F(c.b));
                    if (c.a < 0.99f) mtl.AppendLine("d " + F(c.a));
                    mtl.AppendLine();
                }
                obj.AppendLine("usemtl " + matName);
                Vector3[] vs = m.vertices;
                Vector3[] ns = m.normals;
                for (int i = 0; i < vs.Length; i++)
                {
                    Vector3 p = t.TransformPoint(vs[i]);
                    obj.AppendLine("v " + F(-p.x) + " " + F(p.y) + " " + F(p.z));
                }
                for (int i = 0; i < ns.Length; i++)
                {
                    Vector3 n = t.TransformDirection(ns[i]).normalized;
                    obj.AppendLine("vn " + F(-n.x) + " " + F(n.y) + " " + F(n.z));
                }
                bool hasN = ns.Length == vs.Length;
                for (int s = 0; s < m.subMeshCount; s++)
                {
                    int[] tri = m.GetTriangles(s);
                    for (int i = 0; i + 2 < tri.Length; i += 3)
                    {
                        // Mirroring X flips handedness, so reverse the winding.
                        int a = tri[i], b = tri[i + 2], cc = tri[i + 1];
                        if (hasN) obj.AppendLine("f " + (a + vBase) + "//" + (a + nBase) + " " + (b + vBase) + "//" + (b + nBase) + " " + (cc + vBase) + "//" + (cc + nBase));
                        else obj.AppendLine("f " + (a + vBase) + " " + (b + vBase) + " " + (cc + vBase));
                    }
                }
                vBase += vs.Length;
                if (hasN) nBase += ns.Length;
            }
        }
        File.WriteAllText(Path.Combine(OutDir, level.id + ".obj"), obj.ToString(), new UTF8Encoding(false));
        File.WriteAllText(Path.Combine(OutDir, level.id + ".mtl"), mtl.ToString(), new UTF8Encoding(false));
        Object.DestroyImmediate(refFig.gameObject);
    }

    static void WriteTable(LevelData level, Stage stage, StringBuilder doc)
    {
        doc.AppendLine("## " + level.id + " " + level.title);
        doc.AppendLine();
        var places = new HashSet<string>();
        FieldData place = level.FindField(Simulator.PlaceField);
        if (place != null) foreach (OptionData o in place.options) places.Add(o.id);
        var clues = new HashSet<string>();
        foreach (ClueData c in level.clues) clues.Add(c.anchor);

        doc.AppendLine("| 锚点 | 类型 | 原点 (x, y, z) | 灰盒包围盒 宽×高×深 | 包围盒中心相对原点 | spin | toggle | light | 线索 |");
        doc.AppendLine("|---|---|---|---|---|---|---|---|---|");
        var ids = new List<string>();
        foreach (AnchorTag t in stage.AllAnchors) ids.Add(t.id);
        ids.Sort(System.StringComparer.Ordinal);
        foreach (string id in ids)
        {
            AnchorTag t = stage.Find(id);
            Vector3 o = t.transform.position;
            Bounds b = new Bounds();
            bool any = false;
            foreach (Renderer r in t.GetComponentsInChildren<Renderer>(true))
            {
                if (r is ParticleSystemRenderer || IsProgram(r)) continue;
                if (!any) { b = r.bounds; any = true; } else b.Encapsulate(r.bounds);
            }
            ModelSwap.Uses u = StageBuilder.UsesOf(level, t);
            string kind = places.Contains(id) ? "地点" : (t.isFigure ? "NPC" : "物件");
            string size = any ? F(b.size.x) + " × " + F(b.size.y) + " × " + F(b.size.z) : "—";
            Vector3 off = any ? b.center - o : Vector3.zero;
            string offs = any ? "(" + F(off.x) + ", " + F(off.y) + ", " + F(off.z) + ")" : "—";
            doc.AppendLine("| `" + id + "` | " + kind + " | (" + F(o.x) + ", " + F(o.y) + ", " + F(o.z) + ") | " + size + " | " + offs + " | " +
                           (u.spin ? "✓" : "") + " | " + (u.toggle ? "✓" + (t.toggleMotion != null ? "（铰链）" : "") : "") + " | " + (u.light ? "✓" : "") + " | " + (clues.Contains(id) ? "✓" : "") + " |");
        }
        doc.AppendLine();
    }
}
